<?php
declare(strict_types=1);
// Đội xe & tài xế (tài xế đi theo xe): quản lý chỉ cấp cao; xuất kho đi bắt buộc chọn xe + tài xế xác nhận đủ hàng;
// kho đến kiểm tra hàng đủ / đúng tài xế; báo sai lệch; sửa / xoá xe và tài xế.
require __DIR__ . '/../Support/bootstrap.php';

use StockFlow\Domain\DomainError;
use StockFlow\Domain\Forbidden;
use StockFlow\Service\FleetService;
use StockFlow\Service\TransferService;
use StockFlow\Service\VoucherRepository;

$f = Fx::make();
$fleet = $f->c->get(FleetService::class);
$ts = $f->c->get(TransferService::class);
$repo = $f->c->get(VoucherRepository::class);
$cccd = fn() => (string)random_int(100000000000, 999999999999);
$tripOf = fn(int $outId) => $f->db->one('SELECT * FROM chuyen_van_chuyen WHERE phieu_di_id = ?', [$outId]);

section('Quản lý xe & tài xế: chỉ tài khoản cấp cao');
throws(fn() => $fleet->addVehicle($f->approverA, '30H-123.45', 'Xe tải', $f->wa), Forbidden::class, 'quản lý kho không thêm được xe');
throws(fn() => $fleet->addDriver($f->keeperA, 'Nguyễn Văn A', $cccd(), ''), Forbidden::class, 'nhân viên kho không thêm được tài xế');
$d1cccd = $cccd();
$d1 = $fleet->addDriver($f->admin, 'Trần Văn Tài', $d1cccd, '0912345678');
$d2 = $fleet->addDriver($f->admin, 'Lê Văn Lái', $cccd(), '');
$d3 = $fleet->addDriver($f->admin, 'Phạm Văn Xe', $cccd(), '');
throws(fn() => $fleet->addDriver($f->admin, 'Người khác', $d1cccd, ''), DomainError::class, 'trùng CCCD bị từ chối');
throws(fn() => $fleet->addDriver($f->admin, 'Sai CCCD', '12345', ''), DomainError::class, 'CCCD phải đủ 12 số');
$xe1 = $fleet->addVehicle($f->admin, '30h-' . random_int(100, 999) . '.' . random_int(10, 99), 'Xe tải 2 tấn', $f->wa, $d1);
same((int)$f->db->value('SELECT kho_hien_tai_id FROM xe WHERE id = ?', [$xe1]), $f->wa, 'xe mới đứng ở kho gốc');
same((int)$f->db->value('SELECT tai_xe_id FROM xe WHERE id = ?', [$xe1]), $d1, 'tài xế gắn với xe');
throws(fn() => $fleet->addVehicle($f->admin, '29C-' . random_int(10000, 99999), '', $f->wa, $d1), DomainError::class, 'một tài xế không phụ trách hai xe');
$xe2 = $fleet->addVehicle($f->admin, '29C-' . random_int(10000, 99999), '', $f->wa, $d2);
throws(fn() => $fleet->addVehicle($f->admin, '51C-' . random_int(10000, 99999), '', $f->wa, $d3), DomainError::class, 'mỗi kho tối đa 2 xe');
throws(fn() => $fleet->addVehicle($f->admin, 'abc', '', $f->wb), DomainError::class, 'biển số sai định dạng bị từ chối');
$plateB = '43A-' . random_int(10000, 99999);
$xeB = $fleet->addVehicle($f->admin, $plateB, '', $f->wb, null);
throws(fn() => $fleet->addVehicle($f->admin, $plateB, '', $f->wb), DomainError::class, 'trùng biển số bị từ chối');
same(count($fleet->availableVehicles($f->wa)), 2, 'kho A có 2 xe sẵn sàng');

section('Xuất kho đi: chọn xe — tài xế đi theo xe — và tài xế xác nhận đủ hàng');
$f->receive($f->wa, 'x', 100);
$t = $ts->createDraft($f->keeperA, $f->wa, $f->wb, [$f->line('x', 30)], 'test', null)['voucher'];
$tid = (int)$t['id'];
throws(fn() => $ts->dispatch($f->approverA, $tid, 0, true), DomainError::class, 'chưa chọn xe bị từ chối');
throws(fn() => $ts->dispatch($f->approverA, $tid, $xe1, false), DomainError::class, 'tài xế chưa xác nhận đủ hàng bị từ chối');
throws(fn() => $ts->dispatch($f->keeperA, $tid, $xe1, true), Forbidden::class, 'nhân viên không có quyền xuất kho đi');
throws(fn() => $ts->dispatch($f->approverA, $tid, $xeB, true), DomainError::class, 'xe đang đứng ở kho khác không chọn được');
$xeNoDriver = $fleet->addVehicle($f->admin, '51D-' . random_int(10000, 99999), '', $f->wb, null);
$f->db->exec('UPDATE xe SET kho_hien_tai_id = ? WHERE id = ?', [$f->wa, $xeNoDriver]);
throws(fn() => $ts->dispatch($f->approverA, $tid, $xeNoDriver, true), DomainError::class, 'xe chưa có tài xế phụ trách không xuất kho được');
$f->db->exec('UPDATE xe SET kho_hien_tai_id = ? WHERE id = ?', [$f->wb, $xeNoDriver]);
$fleet->deleteVehicle($f->admin, $xeNoDriver);
same($repo->find($tid)['trang_thai'], 'DRAFT', 'các lần bị từ chối không làm đổi phiếu');
same($f->stock($f->wa, 'x'), 100, 'tồn kho đi chưa bị trừ');
$ts->dispatch($f->approverA, $tid, $xe1, true);
same($repo->find($tid)['trang_thai'], 'CONFIRMED', 'xuất kho đi thành công');
same($f->stock($f->wa, 'x'), 70, 'tồn kho đi đã trừ');
$trip = $tripOf($tid);
same([(int)$trip['xe_id'], (int)$trip['tai_xe_id'], $trip['trang_thai'], (int)$trip['tai_xe_xac_nhan_du_hang']], [$xe1, $d1, 'IN_TRANSIT', 1], 'chuyến ghi đúng xe và tài xế phụ trách xe đó');
$x = $f->db->one('SELECT * FROM xe WHERE id = ?', [$xe1]);
same([$x['kho_hien_tai_id'], (int)$x['dang_den_kho_id']], [null, $f->wb], 'xe đang chạy tới kho B');
same(count($fleet->availableVehicles($f->wa)), 1, 'kho A còn 1 xe sẵn sàng');
$t2 = $ts->createDraft($f->keeperA, $f->wa, $f->wb, [$f->line('x', 5)], 'test', null)['voucher'];
throws(fn() => $ts->dispatch($f->approverA, (int)$t2['id'], $xe1, true), DomainError::class, 'xe đang chạy (cùng tài xế) không chọn lại được');
throws(fn() => $fleet->setVehicleActive($f->admin, $xe1, false), DomainError::class, 'xe đang chạy không ngừng được');
throws(fn() => $fleet->setDriverActive($f->admin, $d1, false), DomainError::class, 'tài xế đang chạy không ngừng được');
throws(fn() => $fleet->updateVehicle($f->admin, $xe1, $x['bien_so'], '', $f->wa, $d3), DomainError::class, 'xe đang chạy không đổi được tài xế');
$again = $ts->dispatch($f->approverA, $tid, $xe2, true);
same($again['already'], true, 'xuất kho đi lần hai chỉ báo «đã xác nhận trước đó»');
same((int)$f->db->value('SELECT COUNT(*) FROM chuyen_van_chuyen WHERE phieu_di_id = ?', [$tid]), 1, 'không sinh thêm chuyến');
same($f->stock($f->wa, 'x'), 70, 'tồn kho đi không bị trừ lần nữa');

section('Kho đến kiểm tra: hàng đủ + đúng tài xế mới nhận được');
$in = $repo->pairOf($repo->find($tid));
$inId = (int)$in['id'];
$v = $repo->find($inId);
same($fleet->tripOf($v)['bien_so'], $x['bien_so'], 'phiếu đến thấy cùng thông tin xe');
same($fleet->tripOf($v)['tai_xe_ten'], 'Trần Văn Tài', 'phiếu đến thấy tài xế của xe');
throws(fn() => $ts->receiveChecked($f->approverB, $inId, true, false), DomainError::class, 'sai tài xế không nhận được');
throws(fn() => $ts->receiveChecked($f->approverB, $inId, false, true), DomainError::class, 'hàng không đủ không nhận được');
throws(fn() => $ts->receiveChecked($f->approverA, $inId, true, true), Forbidden::class, 'kho đi không nhận thay kho đến');
same($f->stock($f->wb, 'x'), 0, 'tồn kho đến chưa cộng');
throws(fn() => $ts->reportDiscrepancy($f->approverB, $inId, false, true, ''), DomainError::class, 'báo sai lệch bắt buộc ghi lý do');
throws(fn() => $ts->reportDiscrepancy($f->approverB, $inId, true, true, 'không có gì'), DomainError::class, 'hàng đủ + đúng tài xế thì không báo sai lệch');
$ts->reportDiscrepancy($f->approverB, $inId, false, true, 'thiếu 5 cái');
$trip = $tripOf($tid);
truthy(str_contains($trip['sai_lech'], 'hàng không đủ') && str_contains($trip['sai_lech'], 'thiếu 5 cái'), 'sai lệch được ghi lại kèm lý do');
same([$trip['trang_thai'], $repo->find($inId)['trang_thai'], $f->stock($f->wb, 'x')], ['IN_TRANSIT', 'DRAFT', 0], 'báo sai lệch: hàng vẫn đang vận chuyển, chưa cộng tồn');
same($fleet->openDiscrepancies() >= 1, true, 'trang Đội xe đếm được chuyến có sai lệch');
$ts->receiveChecked($f->approverB, $inId, true, true);
same([$tripOf($tid)['trang_thai'], $repo->find($inId)['trang_thai'], $f->stock($f->wb, 'x')], ['DELIVERED', 'CONFIRMED', 30], 'sau khi xử lý xong: nhận hàng, cộng tồn kho đến');
$x = $f->db->one('SELECT * FROM xe WHERE id = ?', [$xe1]);
same([(int)$x['kho_hien_tai_id'], $x['dang_den_kho_id']], [$f->wb, null], 'xe đã tới kho B');
same(count(array_filter($fleet->availableVehicles($f->wb), fn($v) => $v['tai_xe_id'] !== null)), 1, 'kho B có xe (kèm tài xế) của kho A đang đứng, dùng được cho chuyến kế tiếp');
$fleet->setVehicleActive($f->admin, $xe1, false);
same(in_array($xe1, array_map(fn($v) => (int)$v['id'], $fleet->availableVehicles($f->wb)), true), false, 'xe ngừng dùng không còn được chọn');
$fleet->setVehicleActive($f->admin, $xe1, true);
$fleet->relocateVehicle($f->admin, $xe1, $f->wa);
same((int)$f->db->value('SELECT kho_hien_tai_id FROM xe WHERE id = ?', [$xe1]), $f->wa, 'quản trị điều xe về kho A');

section('Phiếu điều chuyển cũ không có chuyến vẫn nhận được');
$old = $ts->createDraft($f->keeperA, $f->wa, $f->wb, [$f->line('x', 4)], 'cũ', null)['voucher'];
$ts->confirm($f->approverA, (int)$old['id']);
$oldIn = $repo->pairOf($repo->find((int)$old['id']));
$ts->receiveChecked($f->approverB, (int)$oldIn['id'], false, false);
same($repo->find((int)$oldIn['id'])['trang_thai'], 'CONFIRMED', 'phiếu không có thông tin xe nhận như trước');

section('Sửa và xoá xe, tài xế');
$spare = $fleet->addVehicle($f->admin, '88A-' . random_int(10000, 99999), 'Xe nháp', $f->wb, $d3);
throws(fn() => $fleet->updateVehicle($f->approverB, $spare, '88A-12345', '', $f->wb, $d3), Forbidden::class, 'quản lý kho không sửa được xe');
throws(fn() => $fleet->updateVehicle($f->admin, $spare, $plateB, '', $f->wb, $d3), DomainError::class, 'sửa trùng biển số xe khác bị từ chối');
throws(fn() => $fleet->updateVehicle($f->admin, $spare, 'sai', '', $f->wb, $d3), DomainError::class, 'sửa sang biển số sai định dạng bị từ chối');
throws(fn() => $fleet->updateVehicle($f->admin, $spare, '88A-54321', '', $f->wa, $d3), DomainError::class, 'đổi sang kho gốc đã đủ 2 xe bị từ chối');
throws(fn() => $fleet->updateVehicle($f->admin, $spare, '88A-54321', '', $f->wb, $d2), DomainError::class, 'đổi sang tài xế đang phụ trách xe khác bị từ chối');
$newPlate = '88A-' . random_int(10000, 99999);
$fleet->updateVehicle($f->admin, $spare, strtolower($newPlate), 'Xe tải 3 tấn', $f->wb, $d3);
same($f->db->one('SELECT bien_so, loai_xe FROM xe WHERE id = ?', [$spare]), ['bien_so' => $newPlate, 'loai_xe' => 'Xe tải 3 tấn'], 'sửa xe: biển số được chuẩn hoá, loại xe cập nhật');
throws(fn() => $fleet->deleteDriver($f->admin, $d3), DomainError::class, 'tài xế đang phụ trách xe không xoá được');
throws(fn() => $fleet->deleteVehicle($f->approverB, $spare), Forbidden::class, 'quản lý kho không xoá được xe');
throws(fn() => $fleet->deleteVehicle($f->admin, $xe1), DomainError::class, 'xe đã có chuyến trong lịch sử không xoá được');
$fleet->deleteVehicle($f->admin, $spare);
same((int)$f->db->value('SELECT COUNT(*) FROM xe WHERE id = ?', [$spare]), 0, 'xe chưa từng chạy xoá được');
$d5 = $fleet->addDriver($f->admin, 'Tài xế dự phòng', $cccd(), '');
throws(fn() => $fleet->updateDriver($f->admin, $d5, 'Tên mới', $d1cccd, ''), DomainError::class, 'sửa trùng CCCD tài xế khác bị từ chối');
$fleet->updateDriver($f->admin, $d5, '  Phạm   Văn Dự ', $cccd(), '0987654321');
same($f->db->one('SELECT ho_ten, so_dien_thoai FROM tai_xe WHERE id = ?', [$d5]), ['ho_ten' => 'Phạm Văn Dự', 'so_dien_thoai' => '0987654321'], 'sửa tài xế: họ tên được gọn lại');
throws(fn() => $fleet->deleteDriver($f->admin, $d1), DomainError::class, 'tài xế đã có chuyến trong lịch sử không xoá được');
$fleet->deleteDriver($f->admin, $d5);
same((int)$f->db->value('SELECT COUNT(*) FROM tai_xe WHERE id = ?', [$d5]), 0, 'tài xế chưa từng chạy xoá được');
$t5 = $ts->createDraft($f->keeperA, $f->wa, $f->wb, [$f->line('x', 3)], 'test', null)['voucher'];
$ts->dispatch($f->approverA, (int)$t5['id'], $xe2, true);
throws(fn() => $fleet->updateDriver($f->admin, $d2, 'Đổi tên', $cccd(), ''), DomainError::class, 'tài xế đang chạy không sửa được');
throws(fn() => $fleet->deleteVehicle($f->admin, $xe2), DomainError::class, 'xe đang chạy không xoá được');

finish();
